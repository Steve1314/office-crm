const languageIndexes = { en: -1, gu: 0, hi: 1 };

function getInitialLanguage() {
  try {
    const savedLanguage = window.localStorage.getItem('office-crm-language');
    return Object.prototype.hasOwnProperty.call(languageIndexes, savedLanguage) ? savedLanguage : 'en';
  } catch (error) {
    console.warn('Could not read saved language preference:', error);
    return 'en';
  }
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(getInitialLanguage);

  useEffect(() => {
    document.documentElement.lang = language;
    try {
      window.localStorage.setItem('office-crm-language', language);
    } catch (error) {
      console.warn('Could not save language preference:', error);
    }
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (englishText) => {
      if (language === 'en') return englishText;
      const translation = translations[englishText];
      return translation?.[languageIndexes[language]] || englishText;
    }
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}
